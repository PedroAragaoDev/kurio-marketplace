import { test, expect, type Page } from '@playwright/test'
import { addNft, login, ready } from './helpers'

async function accountData(page: Page, path: string) {
  return page.evaluate(async (path) => {
    const session = await (await fetch('/api/session')).json()
    return (await fetch(`/api${path}`, { headers: { 'X-Session': session.nonce } })).json()
  }, path)
}
async function checkout(page: Page) {
  await ready(page); await login(page); await addNft(page); await page.goto('/pagamento')
  await expect(page.getByLabel('Endereço da carteira *', { exact: true })).toHaveValue(`0x${'a'.repeat(40)}`)
}

test('campos do Figma e carteiras aparecem com confirmação abaixo do total', async ({ page }) => {
  await checkout(page)
  await expect(page.getByLabel('Rede *', { exact: true })).toHaveValue('Ethereum')
  await expect(page.getByLabel('Tipo de carteira *', { exact: true })).toHaveValue('MetaMask')
  await expect(page.getByLabel('ENS ou carteira secundária (opcional)', { exact: true })).toBeVisible()
  const summary = page.locator('.checkout-summary')
  await expect(summary.getByRole('radio')).toHaveCount(1)
  await expect(summary.getByRole('radio')).toBeChecked()
  await expect(summary.getByRole('button')).toHaveCount(1)
  await expect(summary.getByRole('link', { name: 'Cadastrar ou editar carteiras' })).toBeVisible()
  await expect(summary.getByText('Demonstração · Nenhum pagamento real será efetuado.')).toHaveCount(0)
  const total = await summary.locator('.total').boundingBox()
  const wallet = await summary.locator('.wallet-selection').boundingBox()
  const confirm = await summary.getByRole('button', { name: 'Confirmar compra', exact: true }).boundingBox()
  expect(wallet!.y).toBeGreaterThan(total!.y + total!.height)
  expect(confirm!.y).toBeGreaterThan(wallet!.y + wallet!.height)
  await summary.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Revise sua compra' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Confirmar compra', exact: true })).toBeFocused()
})

test('dados da carteira validam, persistem e entram no pedido sem alterar o cadastro', async ({ page }) => {
  await checkout(page)
  const originalWallets = await accountData(page, '/wallets')
  await page.getByLabel('Usar outra carteira?', { exact: true }).check()
  const address = page.getByLabel('Endereço da carteira *', { exact: true })
  await address.fill('inválido')
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(address).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const alternateAddress = `0x${'c'.repeat(40)}`
  await address.fill(alternateAddress)
  await page.getByLabel('Rede *', { exact: true }).selectOption('Base')
  await page.getByLabel('Tipo de carteira *', { exact: true }).selectOption('Coinbase Wallet')
  await page.getByLabel('ENS ou carteira secundária (opcional)', { exact: true }).fill('ana.eth')
  await page.getByLabel('Observação do colecionador (opcional)', { exact: true }).fill('Guardar na coleção principal.\nEdição limitada.')
  await page.reload()
  await expect(address).toHaveValue(alternateAddress)
  await expect(page.getByLabel('Rede *', { exact: true })).toHaveValue('Base')
  await expect(page.getByLabel('Tipo de carteira *', { exact: true })).toHaveValue('Coinbase Wallet')
  await expect(page.getByLabel('ENS ou carteira secundária (opcional)', { exact: true })).toHaveValue('ana.eth')
  await page.getByLabel('Rede *', { exact: true }).selectOption('Polygon')
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Compra confirmada' })).toBeVisible()
  const [order] = await accountData(page, '/orders')
  expect(order.wallet).toMatchObject({ address: alternateAddress, network: 'Polygon', provider: 'Coinbase Wallet' })
  expect(order.collector).toMatchObject({ secondaryWallet: 'ana.eth', notes: 'Guardar na coleção principal.\nEdição limitada.' })
  expect(await accountData(page, '/wallets')).toEqual(originalWallets)
})

const secondaryWallet = () => ({ label: 'Secundária', address: `0x${'d'.repeat(40)}`, network: 'Polygon', provider: 'WalletConnect' })

test('carteira secundária fica pronta ao selecionar e continua selecionada após refresh', async ({ page }) => {
  await checkout(page)
  const secondary = secondaryWallet()
  await page.getByRole('link', { name: 'Cadastrar ou editar carteiras' }).click()
  await page.getByRole('button', { name: 'Adicionar carteira secundária' }).click()
  const form = page.locator('.wallet-form').filter({ has: page.getByRole('heading', { name: 'Carteira secundária', exact: true }) })
  await form.getByLabel('Nome de exibição *', { exact: true }).fill(secondary.label)
  await form.getByLabel('Endereço da carteira *', { exact: true }).fill(secondary.address)
  await form.getByLabel('Rede *', { exact: true }).selectOption(secondary.network)
  await form.getByLabel('Tipo de carteira *', { exact: true }).selectOption(secondary.provider)
  await form.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(page.locator('.toast')).toContainText('Carteira salva')
  await page.goto('/pagamento')
  const radio = page.getByRole('radio', { name: /Secundária/ })
  await radio.check()
  await expect(page.getByLabel('Endereço da carteira *', { exact: true })).toHaveValue(secondary.address)
  await page.reload()
  await expect(radio).toBeChecked()
  await expect(page.getByLabel('Rede *', { exact: true })).toHaveValue(secondary.network)
  await expect(page.getByLabel('Tipo de carteira *', { exact: true })).toHaveValue(secondary.provider)
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Carteira: Secundária')
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Compra confirmada' })).toBeVisible()
  const [order] = await accountData(page, '/orders')
  expect(order.wallet).toMatchObject({ label: secondary.label, address: secondary.address, network: secondary.network, provider: secondary.provider })
})
