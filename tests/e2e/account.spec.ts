import { test, expect } from '@playwright/test'
import { demo, login, ready, scenario } from './helpers'

test('cadastro valida senha e conflito, cria conta e recupera sessão', async ({ page }) => {
  await ready(page); await page.goto('/cadastro')
  await page.getByLabel('Nome de usuário', { exact: true }).fill('colecionador.teste')
  await page.getByLabel('E-mail', { exact: true }).fill('ana@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Colecionador!2026')
  await page.getByLabel('Confirmar senha', { exact: true }).fill('Diferente!2026')
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click(); await expect(page.getByText('As senhas devem ser iguais', { exact: true })).toBeVisible()
  await page.getByLabel('Confirmar senha', { exact: true }).fill('Colecionador!2026')
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click(); await expect(page.getByRole('alert')).toContainText('já está cadastrado')
  await page.getByLabel('E-mail', { exact: true }).fill('novo@kurio.test')
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click(); await expect(page.locator('.account-link')).toBeVisible()
  await page.reload(); await expect(page.locator('.account-link')).toBeVisible()
})
test('favoritos otimistas fazem rollback e não vazam entre usuários', async ({ page }) => {
  await ready(page); await login(page); await scenario(page, 'favorite-error')
  const heart = page.locator('.nft-card').first().getByRole('button', { name: 'Adicionar aos favoritos' })
  await heart.click(); await expect(page.locator('.toast')).toContainText('Não foi possível atualizar')
  await expect(heart).toHaveAttribute('aria-pressed', 'false')
  await scenario(page, 'standard'); await heart.click(); await expect(page.locator('.nft-card').first().getByRole('button', { name: 'Remover dos favoritos' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.toast')).toContainText('Favoritos atualizados.')
  await page.goto('/favoritos'); await expect(page.locator('.nft-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Sair', exact: true }).click(); await login(page, 'bruno')
  await page.goto('/favoritos'); await expect(page.getByRole('heading', { name: 'Sua coleção de favoritos começa aqui' })).toBeVisible()
})
test('perfil, avatar, senha e carteiras validam e persistem', async ({ page }) => {
  await ready(page); await login(page); await page.goto('/perfil')
  await page.getByLabel('Nome de exibição *', { exact: true }).fill('Ana Colecionadora')
  await page.getByLabel('Avatar (até 250 KB)', { exact: true }).setInputFiles('public/art/sage.png')
  await page.getByRole('button', { name: 'Salvar perfil', exact: true }).click(); await expect(page.locator('.toast')).toContainText('Perfil atualizado')
  await page.reload(); await expect(page.getByLabel('Nome de exibição *', { exact: true })).toHaveValue('Ana Colecionadora')
  await expect(page.getByAltText('Seu avatar')).toBeVisible()
  await page.getByLabel('Senha atual', { exact: true }).fill('errada')
  await page.getByLabel('Nova senha', { exact: true }).fill('NovaSenha!2026'); await page.getByLabel('Confirmar nova senha', { exact: true }).fill('NovaSenha!2026')
  await page.getByRole('button', { name: 'Salvar nova senha' }).click(); await expect(page.getByRole('alert')).toContainText('Senha atual incorreta')
  await page.getByLabel('Senha atual', { exact: true }).fill('Colecionador!2026'); await page.getByRole('button', { name: 'Salvar nova senha' }).click(); await expect(page.locator('.toast')).toContainText('Senha alterada')
  await page.goto('/carteiras'); await page.getByLabel('Nome de exibição *', { exact: true }).fill('Reserva')
  await page.getByLabel('Endereço da carteira *', { exact: true }).fill('inválido'); await page.getByRole('button', { name: 'Salvar carteira' }).click(); await expect(page.getByText('Informe um endereço 0x com 40 caracteres hexadecimais')).toBeVisible()
  await page.getByLabel('Endereço da carteira *', { exact: true }).fill(`0x${'c'.repeat(40)}`); await page.getByRole('button', { name: 'Salvar carteira' }).click(); await expect(page.locator('.toast')).toContainText('Carteira salva')
  await page.reload(); await expect(page.getByLabel('Nome de exibição *', { exact: true })).toHaveValue('Reserva')
})
test('expiração preserva checkout; teclado e foco do diálogo', async ({ page, isMobile }) => {
  await ready(page)
  if (isMobile) {
    await page.getByRole('button', { name: 'Abrir filtros' }).click(); await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape'); await expect(page.getByRole('button', { name: 'Abrir filtros' })).toBeFocused()
  }
  await login(page); await page.goto('/pagamento')
  await demo(page, '/action', { action: 'expire' }); await page.goto('/perfil')
  await expect(page).toHaveURL(/\/login/)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveAttribute('aria-invalid', 'true')
})
