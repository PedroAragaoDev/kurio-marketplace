import { test, expect } from '@playwright/test'
import { addNft, demo, login, ready, review, scenario } from './helpers'

test('carrinho visitante persiste após refresh e login, cupom e quantidade', async ({ page }) => {
  await addNft(page)
  await page.getByRole('button', { name: 'Aumentar Emerald Ape #042' }).click()
  await expect(page.getByRole('spinbutton')).toHaveValue('2')
  await page.reload(); await expect(page.getByRole('spinbutton')).toHaveValue('2')
  await login(page); await page.goto('/carrinho'); await expect(page.getByRole('spinbutton')).toHaveValue('2')
  await page.getByLabel('Código promocional').fill('EXPIRED'); await page.getByRole('button', { name: 'Aplicar', exact: true }).click(); await expect(page.locator('.toast')).toContainText('expirou')
  await page.getByLabel('Código promocional').fill('KURIO10'); await page.getByRole('button', { name: 'Aplicar', exact: true }).click(); await expect(page.getByRole('button', { name: 'Remover cupom KURIO10' })).toBeVisible()
  await expect(page.locator('.total')).toContainText('2,1436 ETH')
  await page.getByRole('button', { name: 'Remover Emerald Ape #042' }).click(); await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio' })).toBeVisible()
})
test('compra completa e recibo imutável', async ({ page }, testInfo) => {
  await ready(page); await login(page); await addNft(page); await review(page)
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect(page.getByRole('heading', { name: 'Compra confirmada' })).toBeVisible()
  await expect(page.locator('.receipt .total')).toContainText('1,1916 ETH')
  await expect(page.locator('.receipt')).not.toContainText(/simula|demonstra|fict[íi]ci/i)
  await expect(page.locator('.receipt').getByRole('button')).toHaveCount(0)
  await expect(page.locator('.receipt').getByRole('link', { name: 'Continuar explorando' })).toBeVisible()
  await page.locator('.receipt').screenshot({ path: testInfo.outputPath('recibo.png'), style: '.skip-link, .mobile-nav { visibility: hidden !important; }' })
  await demo(page, '/action', { action: 'price' }); await page.reload()
  await expect(page.locator('.receipt .total')).toContainText('1,1916 ETH')
  await page.goto('/carrinho'); await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio' })).toBeVisible()
})
test('recusa preserva carrinho', async ({ page }) => {
  await ready(page); await login(page); await addNft(page); await scenario(page, 'payment-refused'); await review(page)
  await page.getByRole('button', { name: 'Confirmar compra' }).click(); await expect(page.getByRole('heading', { name: 'Pagamento recusado' })).toBeVisible()
  await page.getByRole('link', { name: 'Voltar ao carrinho' }).click(); await expect(page.getByRole('spinbutton')).toHaveValue('1')
})
test('timeout e cliques repetidos recuperam o mesmo pedido após refresh', async ({ page }) => {
  await ready(page); await login(page); await addNft(page); await scenario(page, 'order-timeout'); await review(page)
  await page.getByRole('button', { name: 'Confirmar compra' }).dblclick()
  await expect(page.getByRole('alert').filter({ hasText: 'A resposta demorou' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Recuperar tentativa' })).toBeEnabled(); await page.reload()
  await page.getByRole('button', { name: 'Recuperar tentativa' }).click(); await expect(page.getByRole('heading', { name: 'Compra confirmada' })).toBeVisible()
  await page.goto('/pedidos'); await expect(page.locator('.orders-list a')).toHaveCount(1)
})
test('Socket.IO altera cotação; duplicatas e eventos antigos não regridem estado', async ({ page }) => {
  await ready(page); await login(page); await addNft(page); await review(page)
  await expect(page.locator('main#conteudo')).toHaveAttribute('data-connection-state', 'connected')
  await demo(page, '/action', { action: 'price' }); await expect(page.locator('.checkout-summary .total')).toContainText('2,1916 ETH')
  await expect(page.getByRole('button', { name: 'Confirmar compra' })).toBeDisabled()
  await demo(page, '/action', { action: 'duplicate' }); await demo(page, '/action', { action: 'old' })
  await expect(page.locator('.checkout-summary .total')).toContainText('2,1916 ETH')
  await page.getByRole('button', { name: 'Voltar aos dados' }).click(); await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar compra' }).click(); await expect(page.getByRole('heading', { name: 'Compra confirmada' })).toBeVisible()
})
test('pedido pendente recupera após desconexão e refresh', async ({ page }) => {
  await ready(page); await login(page); await addNft(page); await scenario(page, 'pending'); await review(page)
  await page.getByRole('button', { name: 'Confirmar compra' }).click(); await expect(page.getByRole('heading', { name: 'Pedido pendente' })).toBeVisible()
  if (await page.getByRole('button', { name: 'Dispensar aviso' }).isVisible()) await page.getByRole('button', { name: 'Dispensar aviso' }).click()
  const receipt = page.url()
  await page.goto('/demonstracao'); await expect(page.getByRole('main')).toHaveAttribute('data-connection-state', 'connected')
  await page.getByRole('button', { name: 'Desconectar', exact: true }).click()
  await expect(page.getByRole('main')).toHaveAttribute('data-connection-state', 'disconnected')
  await demo(page, '/action', { action: 'settle' }); await page.goto(receipt); await expect(page.getByRole('heading', { name: 'Compra confirmada' })).toBeVisible()
})
